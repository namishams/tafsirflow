// The app's deterministic hash and shuffle (mobile/src/features/feed/knowledge.ts), copied letter for letter: the same
// quiz question gets the same option order on the app and on the website. Do not change the arithmetic.

export const hash = (s: string) => {
  let h = 2166136261;
  for (const ch of s) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
  return h;
};

export function seeded(seed: number) {
  let x = seed || 1;
  return () => {
    x ^= x << 13;
    x ^= x >>> 17;
    x ^= x << 5;
    return ((x >>> 0) % 100000) / 100000;
  };
}

export function shuffleBy<T>(a: T[], seed: number): T[] {
  const r = seeded(seed);
  const out = [...a];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
