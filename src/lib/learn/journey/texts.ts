// The other twelve languages live in ./i18n/<lang>.json (copied unchanged from the app). The website loads a file the
// first time its language is used (this folder holds only .json files: the dynamic import below bundles all of them).
const own = new Map<string, Partial<Record<JKey, string>> | null>();
const loading = new Set<string>();
const subs = new Set<() => void>();
let ver = 0;
const LANGS = new Set(["ar", "tr", "ur", "fa", "ps", "fr", "es", "id", "ms", "bn", "ru", "zh"]);
function load(lang: string) {
  if (!LANGS.has(lang) || own.has(lang) || loading.has(lang)) return;
  loading.add(lang);
  import(`./i18n/${lang}.json`)
    .then((m: { default: Partial<Record<JKey, string>> }) => { own.set(lang, m.default); })
    .catch(() => { own.set(lang, null); })
    .finally(() => { loading.delete(lang); tables.delete(lang); ver++; subs.forEach((f) => f()); });
}
const subscribe = (f: () => void) => { subs.add(f); return () => { subs.delete(f); }; };
const tables = new Map<string, Record<JKey, string>>();
function table(lang: string): Record<JKey, string> {
  if (lang === "de") return de;
  if (lang === "en" || !LANGS.has(lang)) return en;
  const o = own.get(lang);
  if (!o) return en; // not loaded yet: English now, the language once the file arrived
  if (!tables.has(lang)) tables.set(lang, { ...en, ...o });
  return tables.get(lang)!;
}
export function jText(lang: string, key: JKey, vars?: Record<string, string | number>): string {
  let s = table(lang)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export type JT = (key: JKey, vars?: Record<string, string | number>) => string;
export function useJT(): JT {
  const { lang } = useLang();
  useSyncExternalStore(subscribe, () => ver, () => 0);
  useEffect(() => { load(lang); }, [lang]);
  return (key: JKey, vars?: Record<string, string | number>) => jText(lang, key, vars);
}
