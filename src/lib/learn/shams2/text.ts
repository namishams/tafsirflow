export type S2Key = keyof T;
export type CL = "de" | "en" | "ar";
export const S2_TEXT = { en, de, ar };

/** UI texts (s), content language for de/en/ar content (cl) and number formatting (nf) */
export function useS2() {
  const { lang } = useLang();
  const d = moduleText("shams2", { en, de, ar }, lang);
  const nf = useIntl();
  const s = useCallback((k: S2Key, p?: Record<string, string | number>) => {
    const v = (d as Record<string, string>)[k] ?? (en as Record<string, string>)[k] ?? k;
    return p ? v.replace(/\{(\w+)\}/g, (_, x: string) => String(p[x] ?? "")) : v;
  }, [d]);
  const cl: CL = lang === "de" ? "de" : lang === "ar" ? "ar" : "en";
  return { s, cl, nf, lang };
}
