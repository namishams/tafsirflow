const OTHER: Record<string, Partial<Record<TgKey, string>>> = { ar, tr, ur, fa, ps, fr, es, id, ms, bn, ru, zh };
export function togetherText(locale: string): Record<TgKey, string> {
  if (locale === "de") return de;
  if (locale === "en") return en;
  return { ...en, ...(OTHER[locale] ?? {}) };
}
/** fills {n}-style placeholders */
