import type { Metadata } from "next";
import { setRequestLocale } from "next-intl/server";
import { pageMeta } from "@/lib/site";
import { s2Meta } from "@/components/learn/shams2/meta";
import { WeekScreen } from "@/components/learn/shams2/Guide";

// /shams/week – weekly review (muraja'at al-usbu') (mirrors mobile/src/app/shams/week.tsx)
export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  const m = s2Meta(locale, "week");
  return { ...pageMeta(locale, "/shams/week", m.title, m.description), robots: { index: false, follow: true } };
}

export default async function Page({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  setRequestLocale(locale);
  return <WeekScreen />;
}
