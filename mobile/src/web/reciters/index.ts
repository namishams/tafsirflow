// generated by scripts/sync-web.mjs: the other languages, required only when one is opened
// eslint-disable-next-line @typescript-eslint/no-explicit-any, @typescript-eslint/no-require-imports
function __lang3(p: string): any {
  switch (p) {
    case "./i18n/bn": return require("./i18n/bn");
    case "./i18n/es": return require("./i18n/es");
    case "./i18n/fa": return require("./i18n/fa");
    case "./i18n/fr": return require("./i18n/fr");
    case "./i18n/id": return require("./i18n/id");
    case "./i18n/ms": return require("./i18n/ms");
    case "./i18n/ps": return require("./i18n/ps");
    case "./i18n/ru": return require("./i18n/ru");
    case "./i18n/tr": return require("./i18n/tr");
    case "./i18n/ur": return require("./i18n/ur");
    case "./i18n/zh": return require("./i18n/zh");
  }
  throw new Error("language not bundled");
}
