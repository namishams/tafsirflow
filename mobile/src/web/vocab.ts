export type Word = {
  id: string;
  ar: string;
  tr: string;
  root?: string;
  en: string;
  de: string;
  type: "noun" | "verb" | "particle" | "name" | "pronoun" | "adjective";
  /** the verse the word is learned from (the trainer shows it from the Quran API) and the words of it that hold the
   *  example, `from`..`to`: verseQuote("imlaei", key, from, to) in verseQuotes.ts cuts them out of data/verse-quotes.json.
   *  No Quran text is typed here (BLUEPRINT §4). */
  ex?: { key: string; from: number; to: number };
  /** meanings in the other languages (ar, tr, ur, fa, ps, fr, es, id, ms, bn, ru, zh), filled by vocabFor() in
   *  vocabI18n.ts; read them with meaning(word, locale), which falls back to English */
  meanings?: Partial<Record<"ar" | "tr" | "ur" | "fa" | "ps" | "fr" | "es" | "id" | "ms" | "bn" | "ru" | "zh", string>>;
};

export type Deck = {
  id: string;
  title_en: string;
  title_de: string;
  desc_en: string;
  desc_de: string;
  words: Word[];
};

type T = Word["type"];

function w(id: string, ar: string, tr: string, root: string | null, en: string, de: string, type: T, ex?: [string, number, number]): Word {
  const word: Word = { id, ar, tr, en, de, type };
  if (root) word.root = root;
  if (ex) word.ex = { key: ex[0], from: ex[1], to: ex[2] };
  return word;
}

