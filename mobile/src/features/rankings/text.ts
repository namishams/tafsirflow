export type RKey = keyof typeof S.en;
export function useRT() {
  const { lang } = useLang();
  return (key: RKey, vars?: Record<string, string | number>) => rankingsT(lang, key, vars);
}
export function rankingsT(lang: string, key: RKey, vars?: Record<string, string | number>): string {
  let s = moduleText("rankings", S, lang)[key] ?? S.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
