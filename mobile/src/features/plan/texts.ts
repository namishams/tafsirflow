/** the plan texts in the current language */
export function usePlanT(): PlanStrings {
  const { lang } = useLang();
  return moduleText("plan", { de, en }, lang);
}

/** "{n} min" -> "10 min" */
export const fmt = (s: string, p: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k: string) => (p[k] !== undefined ? String(p[k]) : `{${k}}`));
