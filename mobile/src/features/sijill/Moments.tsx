// Achievement moments: generated by the system when a member reaches something (certificate, exam, level, juz, tree
// stage, legendary sticker, streak, course, Hifz grade). Others answer with a gold heart or one of three preset
// encouragements; no free text, so nothing needs moderation. One reaction per person, tap again to remove it.

/** one line describing a moment, in the viewer's language */
export function useMomentText() {
  const st = useST();
  const gt = useGardenText();
  const { lang } = useLang();
  return (m: Pick<Moment, "kind" | "ref" | "data" | "title">): string => {
    const d = m.data ?? {};
    const num = Number(d.n ?? 0);
    switch (m.kind) {
      case "certificate": return st("mo_certificate", { t: m.title ?? String(d.course ?? "") });
      case "exam": return st("mo_exam", { t: examTitle({ exam: String(d.exam ?? ""), ref: String(d.ref ?? "") }, st) });
      case "level": return st("mo_level", { n: num });
      case "juz": return st("mo_juz", { n: num });
      case "tree": return st("mo_tree", { n: num });
      case "streak": return st("mo_streak", { n: num });
      case "hifz": return st("mo_hifz", { n: num, t: GRADES[num - 1]?.tr ?? "" });
      case "sticker": return typeof d.series === "string" ? st("mo_series", { t: (gt[`ser_${d.series}` as keyof typeof gt] as string) ?? d.series }) : st("mo_sticker");
      case "course": {
        if (typeof d.arabic === "string") return st("mo_arabic", { t: d.arabic });
        const c = typeof d.id === "string" ? courseById(d.id as never) : undefined;
        return c ? st("mo_course", { t: courseTx(c.title, lang) }) : st("mo_courseAny");
      }
    }
    return "";
  };
}

const ICON: Record<Moment["kind"], "starBig" | "checkCircle" | "trophy" | "book" | "sun" | "grid" | "flame" | "cap"> = {
  certificate: "starBig", exam: "checkCircle", level: "trophy", hifz: "trophy", juz: "book", tree: "sun", sticker: "grid", streak: "flame", course: "cap",
};

export function MomentCard({ m, onChange, showAuthor = true }: { m: Moment; onChange: (m: Moment) => void; showAuthor?: boolean }) {
  const t = useTheme();
  const st = useST();
  const err = useTalentErr();
  const text = useMomentText();
  const { lang } = useLang();
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState("");
  const react = async (r: Reaction) => {
    if (m.own || busy) return;
    setBusy(true); setMsg("");
    try {
      const next = m.mine === r ? null : r;
      const d = await sijillApi.react(m.id, next);
      onChange({ ...m, mine: d.mine, counts: d.counts, total: d.total });
    } catch (e) { setMsg(err(e)); } finally { setBusy(false); }
  };
  const line = text(m);
  return (
    <View style={{ borderRadius: R.card, borderWidth: 1, borderColor: t.line, backgroundColor: t.surface, padding: 14, gap: 10 }}>
      {showAuthor ? (
        <Pressable onPress={() => router.push(`/talents/u/${m.author.username}` as Href)} accessibilityRole="link" accessibilityLabel={m.author.name} style={{ flexDirection: "row", alignItems: "center", gap: 10 }}>
          <TalentAvatar name={m.author.name} size={38} uri={m.author.avatar} badge={m.author.badge} />
          <View style={{ flex: 1 }}>
            <View style={{ flexDirection: "row", alignItems: "center", gap: 5 }}>
              <Text numberOfLines={1} style={{ flexShrink: 1, fontFamily: FONT.bold, fontSize: 14.5, color: t.ink }}>{m.own ? st("yourMoment") : m.author.name}</Text>
              {!m.own ? <BadgeButton badge={m.author.badge} size={13} /> : null}
            </View>
            <Text numberOfLines={1} style={{ fontFamily: FONT.regular, fontSize: 12, color: t.muted }}>{`@${m.author.username} · ${new Date(m.at).toLocaleDateString(lang, { day: "numeric", month: "short" })}`}</Text>
          </View>
        </Pressable>
      ) : null}
      <View style={{ flexDirection: "row", alignItems: "center", gap: 10 }}>
        <View style={{ width: 34, height: 34, borderRadius: 17, backgroundColor: "rgb(8,38,29)", borderWidth: 1.5, borderColor: goldButton.line, alignItems: "center", justifyContent: "center" }}>
          <Icon name={ICON[m.kind]} color={goldButton.from} size={16} />
        </View>
        <Text style={{ flex: 1, fontFamily: FONT.semibold, fontSize: 15, lineHeight: 21, color: t.ink }}>{line}</Text>
      </View>
      <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 6 }}>
        {REACTIONS.map((r) => {
          const on = m.mine === r;
          const c = m.counts[r] ?? 0;
          const label = st(`react_${r}` as SKey);
          return (
            <Pressable key={r} onPress={() => void react(r)} disabled={m.own || busy} accessibilityRole="button" accessibilityState={{ selected: on, disabled: m.own }}
              accessibilityLabel={`${on ? st("removeReaction") : label}${c ? `, ${c}` : ""}`}
              style={{ flexDirection: "row", alignItems: "center", gap: 5, minHeight: 34, paddingHorizontal: 11, borderRadius: R.pill, borderWidth: 1,
                borderColor: on ? goldButton.to : t.line, backgroundColor: on ? "rgba(201,166,94,0.16)" : "transparent", opacity: m.own && !c ? 0.55 : 1 }}>
              {r === "like" ? <Icon name="heart" color={on || c ? goldButton.to : t.muted} size={14} /> : null}
              {r !== "like" ? <Text style={{ fontFamily: FONT.semibold, fontSize: 12.5, color: on ? t.ink : t.muted }}>{label}</Text> : null}
              {c ? <Text style={{ fontFamily: FONT.bold, fontSize: 12.5, color: on ? t.ink : t.muted }}>{c}</Text> : null}
            </Pressable>
          );
        })}
      </View>
      {msg ? <Text accessibilityLiveRegion="polite" style={{ fontFamily: FONT.regular, fontSize: 13, color: t.muted }}>{msg}</Text> : null}
    </View>
  );
}

/** the friends stream (people the member follows plus the member) or one member's moments */
export function MomentsFeed({ username, empty }: { username?: string; empty?: string }) {
  const st = useST();
  const err = useTalentErr();
  const { lang } = useLang();
  const [list, setList] = useState<Moment[] | null>(null);
  const [more, setMore] = useState<string | null>(null);
  const [msg, setMsg] = useState("");
  const seq = useRef(0);
  const load = useCallback(async (before?: string) => {
    const my = ++seq.current;
    try {
      const d = await sijillApi.moments({ scope: username ? "user" : "friends", u: username, before, locale: lang });
      if (my !== seq.current) return;
      setList((old) => (before ? [...(old ?? []), ...d.moments] : d.moments)); setMore(d.more);
    } catch (e) { if (my === seq.current) { setMsg(err(e)); setList((x) => x ?? []); } }
  }, [username, lang]); // eslint-disable-line react-hooks/exhaustive-deps
  useEffect(() => { void load(); }, [load]);
  if (!list) return <Loading />;
  if (!list.length) return <Muted>{msg || empty || st("friendsEmpty")}</Muted>;
  return (
    <View style={{ gap: 10 }}>
      {list.map((m) => <MomentCard key={m.id} m={m} showAuthor={!username} onChange={(x) => setList((l) => l?.map((y) => (y.id === x.id ? x : y)) ?? null)} />)}
      {more ? <OutlineButton title={st("loadMore")} onPress={() => void load(more)} /> : null}
    </View>
  );
}
