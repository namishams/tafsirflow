const COL: Record<QLang, 0 | 1 | 2> = { en: 0, de: 1, ar: 2 };

/** "pillars-of-iman" -> "Pillars of iman" (sentence case, as every heading of the app) */
export function humaniseTag(tag: string): string {
  const s = tag.replace(/-/g, " ").trim();
  return s ? s[0].toUpperCase() + s.slice(1) : tag;
}

/** the visible name of a topic tag in the question language; unknown tags read as humanised English */
export function tagLabel(tag: string, lang: QLang = "en"): string {
  const row = ROWS[tag];
  if (!row) return humaniseTag(tag);
  return row[COL[lang] ?? 0] || row[0];
}
