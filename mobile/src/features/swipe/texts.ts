export type SwipeKey = keyof typeof T.en;
export const SWIPE_TEXT_EN = T.en;
export const swipeText = (lang: string, k: SwipeKey, p?: Record<string, string | number>) => {
  const s = moduleText("swipe", T, lang)[k] ?? T.en[k];
  return p ? s.replace(/\{(\w+)\}/g, (_, x: string) => String(p[x] ?? "")) : s;
};
export function useSwipeT() {
  const { lang } = useLang();
  return useCallback((k: SwipeKey, p?: Record<string, string | number>) => swipeText(lang, k, p), [lang]);
}
