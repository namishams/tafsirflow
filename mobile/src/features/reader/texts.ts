export type ReaderKey = keyof typeof T.en;
export function useReaderT() {
  const { lang } = useLang();
  return useCallback((k: ReaderKey, p?: Record<string, string | number>) => {
    const s = moduleText("reader", T, lang)[k] ?? T.en[k];
    return p ? s.replace(/\{(\w+)\}/g, (_, x: string) => String(p[x] ?? "")) : s;
  }, [lang]);
}
