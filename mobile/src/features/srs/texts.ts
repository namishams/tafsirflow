export type SrsKey = keyof typeof T.en;
export const SRS_TEXT_EN = T.en;
export function useSrsT() {
  const { lang } = useLang();
  return useCallback((k: SrsKey, p?: Record<string, string | number>) => {
    const s = moduleText("srs", T, lang)[k] ?? T.en[k];
    return p ? s.replace(/\{(\w+)\}/g, (_, x: string) => String(p[x] ?? "")) : s;
  }, [lang]);
}
