const cache = new Map<string, T>();
export function makhrajText(lang: string): T {
  if (lang === "de") return de;
  if (lang === "ar") return ar;
  if (!LOAD[lang]) return en;
  let d = cache.get(lang);
  if (!d) {
    let tr: Partial<T> = {};
    try { tr = LOAD[lang]() ?? {}; } catch { tr = {}; }
    d = { ...en, ...tr };
    cache.set(lang, d);
  }
  return d;
}
export const fillMk = (s: string, p?: Record<string, string | number>) => (p ? s.replace(/\{(\w+)\}/g, (_, x: string) => String(p[x] ?? "")) : s);
export function useMk() {
  const { lang } = useLang();
  return useCallback((k: MkKey, p?: Record<string, string | number>) => fillMk(makhrajText(lang)[k] ?? en[k], p), [lang]);
}
