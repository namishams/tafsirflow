function appTileColours(src) {
  const tiles = (src.match(/\bkey: "/g) ?? []).length;
  const kept = [], missing = [];
  const merged = src.replace(/^(\s+)(\w+)(: \{ key: "[^"]+",[^\n]*?\bbg: )"[^"]*"/gm, (all, indent, key, mid) => {
    if (!(key in APP_TILE_BG)) { missing.push(key); return all; }
    kept.push(key);
    return `${indent}${key}${mid}${JSON.stringify(APP_TILE_BG[key])}`;
  });
  // fail rather than let the website's colours into the app when the file's layout changed
  if (!tiles || kept.length + missing.length !== tiles) throw new Error("src/lib/tiles.ts: tile lines not recognised, the app's tile colours cannot be kept – adjust appTileColours() in sync-web.mjs");
  if (missing.length) console.warn(`tiles.ts: no app colour for ${missing.join(", ")} – the website's colour is used; add an emerald or gold tone to APP_TILE_BG`);
  return merged;
}
