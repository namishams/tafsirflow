// Copies the website's pure content and learning modules into the app (mobile/src/web), so app and website share
// exactly the same texts, references and learning logic (Shams coach, spaced repetition, courses). Nothing in
// src/web is edited by hand: change the website file and run `npm run sync-web` in mobile/.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..", "..");
const lib = join(site, "src", "lib");
const out = join(here, "..", "src", "web");

// Modules without server, database, Next.js or React code
const FILES = [
  "aboutContent", "academy", "adhan", "age", "arabic", "arabicQuran", "changelog", "coach", "counts", "countries", "duaGenerator",
  "duas", "featured", "guides", "hijri", "journey", "learning", "listen", "mapContent", "plans", "points", "prayer", "quranIndex",
  "recite", "salah", "session", "shamsContent", "stickers", "sunnahDuas", "sunnahDuas2", "tajweed", "tiles",
  "vocab", "votd", "wudu",
];
// Folders copied whole, with the translations of every language the website speaks
const DIRS = ["islam", "names", "reciters", "secrets", "pagecontent"];
const SKIP_DIRS = new Set();

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const rewrite = (src, file) => {
  const depth = relative(out, dirname(file)).split("/").filter(Boolean).length;
  const up = depth ? "../".repeat(depth) : "./";
  return src
    .replace(/^"use client";\n/, "")
    .replace(/from "@\/lib\//g, `from "${up}`)
    // localStorage helpers -> the app's synchronous store (hydrated from AsyncStorage at start)
    .replace(/from "(\.\.?\/)+storage"/g, 'from "@/lib/store"')
    // dynamic imports of other languages: Metro cannot resolve template imports, so each one becomes a lookup in a
    // generated table of static requires (every matching file on disk), loaded only when that language is opened
    .replace(/\(await import\(`([^`]+)`\)\)\.default/g, (_, tpl) => `${dynamicLoader(tpl, file)}(\`${tpl}\`).default`);
};

// "./i18n/${locale}/${d.slug}" -> a function that requires the matching file for a path built at run time
const loaders = new Map();
function dynamicLoader(tpl, file) {
  const fromSite = join(lib, relative(out, dirname(file)));
  const re = new RegExp("^" + tpl.split(/\$\{[^}]+\}/).map((x) => x.replace(/[.*+?^()|[\]\\]/g, "\\$&")).join("([^/]+)") + "$");
  const base = tpl.slice(0, tpl.indexOf("${")).replace(/[^/]*$/, "");
  const paths = [];
  const walk = (dir, rel) => {
    if (!existsSync(dir)) return;
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      const r = `${rel}${name}`;
      if (statSync(p).isDirectory()) walk(p, `${r}/`);
      else if (/\.tsx?$/.test(name) && re.test(r.replace(/\.tsx?$/, ""))) paths.push(r.replace(/\.tsx?$/, ""));
    }
  };
  walk(join(fromSite, base), base);
  const name = `__lang${loaders.size}`;
  const list = loaders.get(file) ?? [];
  list.push({ name, paths: paths.sort() });
  loaders.set(file, list);
  return name;
}
const loaderSource = (list) => list.map(({ name, paths }) =>
  `\n// generated by scripts/sync-web.mjs: the other languages, required only when one is opened\n// eslint-disable-next-line @typescript-eslint/no-explicit-any, @typescript-eslint/no-require-imports\nfunction ${name}(p: string): any {\n  switch (p) {\n${paths.map((x) => `    case ${JSON.stringify(x)}: return require(${JSON.stringify(x)});`).join("\n")}\n  }\n  throw new Error("language not bundled");\n}\n`).join("");

function copyFile(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  const src = rewrite(readFileSync(from, "utf8"), to);
  writeFileSync(to, src + loaderSource(loaders.get(to) ?? []));
}

function copyDir(from, to) {
  for (const name of readdirSync(from)) {
    const p = join(from, name);
    if (statSync(p).isDirectory()) { if (!SKIP_DIRS.has(name)) copyDir(p, join(to, name)); continue; }
    if (/\.(ts|tsx)$/.test(name)) copyFile(p, join(to, name));
    else if (name.endsWith(".json")) cpSync(p, join(to, name));
  }
}

for (const f of FILES) {
  const p = join(lib, `${f}.ts`);
  if (!existsSync(p)) { console.warn(`missing ${f}.ts`); continue; }
  copyFile(p, join(out, `${f}.ts`));
}
for (const d of DIRS) copyDir(join(lib, d), join(out, d));

// UI texts of the website in every language, read by useWebT(), and the list of languages with their direction
mkdirSync(join(out, "messages"), { recursive: true });
for (const name of readdirSync(join(site, "messages"))) if (name.endsWith(".json")) cpSync(join(site, "messages", name), join(out, "messages", name));
copyFile(join(site, "src", "i18n", "locales.ts"), join(out, "locales.ts"));

writeFileSync(join(out, "README.md"), "Generated by scripts/sync-web.mjs from the website (src/lib, messages). Do not edit by hand.\n");
console.log(`synced ${FILES.length} modules and ${DIRS.length} folders into ${relative(site, out)}`);
