// The website names countries with Intl.DisplayNames in the reader's language. Hermes has no DisplayNames, so this
// script writes the same names (Node's full ICU, CLDR) for every website language into src/lib/countries.ts,
// with the website's codes and its order (priority countries first, then alphabetical).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..", "..");
const src = readFileSync(join(site, "src/lib/countries.ts"), "utf8");
const codes = src.match(/COUNTRY_CODES = "([^"]+)"/)[1].split(" ");
const priority = JSON.parse(src.match(/const PRIORITY = (\[[^\]]+\])/)[1]);
const langs = [...readFileSync(join(site, "src/i18n/locales.ts"), "utf8").matchAll(/^  ([a-z]{2}): \{/gm)].map((m) => m[1]);
// Intl tags where the plain code would pick another variant (Dari Persian, Simplified Chinese)
const TAG = { fa: "fa-AF", zh: "zh-Hans" };
const names = {};
for (const code of codes) {
  names[code] = {};
  for (const l of langs) names[code][l] = new Intl.DisplayNames([TAG[l] ?? l], { type: "region" }).of(code) ?? code;
}
const out = `// Generated by scripts/sync-countries.mjs from the website's src/lib/countries.ts – do not edit by hand.
// Country names in every website language, as Intl.DisplayNames gives them on the website (CLDR).
export const COUNTRIES: Record<string, Record<string, string>> = ${JSON.stringify(names)};

const PRIORITY: string[] = ${JSON.stringify(priority)};

export function countryName(code: string, lang: string): string {
  const n = COUNTRIES[code.toUpperCase()];
  return n ? n[lang] ?? n.en : code;
}

/** priority countries first, then the rest alphabetically in the reader's language (website: sortedCountries) */
export function countryList(lang: string): { code: string; name: string }[] {
  const all = Object.keys(COUNTRIES).map((code) => ({ code, name: countryName(code, lang) }));
  const top = PRIORITY.map((c) => all.find((x) => x.code === c)).filter((x): x is { code: string; name: string } => !!x);
  const rest = all.filter((x) => !PRIORITY.includes(x.code)).sort((a, b) => a.name.localeCompare(b.name, lang));
  return [...top, ...rest];
}
`;
writeFileSync(join(here, "..", "src/lib/countries.ts"), out);
console.log(`wrote ${codes.length} countries in ${langs.length} languages`);
