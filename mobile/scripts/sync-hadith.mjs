// Writes src/features/hadith/catalog.ts from the two published hadith APIs, so the app knows the collections, their
// books (sections) and number ranges without downloading a whole collection first. Only metadata is written here –
// the hadith texts themselves are always loaded from the APIs at run time (and cached on the device).
//   node scripts/sync-hadith.mjs
// Sources:
//   fawazahmed0/hadith-api (The Unlicense) https://github.com/fawazahmed0/hadith-api
//   Thaqalayn API (code GPL-3.0, texts and translations from thaqalayn.net) https://www.thaqalayn-api.net
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CDN = "https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1";
const SUNNI = ["bukhari", "muslim", "nawawi"];
// Thaqalayn books shown in the app. Left out on purpose: Nahj al-Balagha (the app uses the owner's own editions) and
// Kitab al-Du'afa (a book of narrator criticism, not of hadith texts).
const SHIA_SKIP = new Set(["Nahj-al-Balagha-Radi", "Kitab-al-Duafa-Ghadairi"]);

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: ${r.status}`);
  return r.json();
};

const editions = await get(`${CDN}/editions.json`);
const info = await get(`${CDN}/info.min.json`);
const sunni = SUNNI.map((key) => {
  const e = editions[key];
  const meta = info[key].metadata;
  const nums = info[key].hadiths.map((h) => h.hadithnumber).filter((n) => Number.isInteger(n));
  const sections = Object.entries(meta.sections)
    .filter(([, name]) => name)
    .map(([n, name]) => {
      const d = meta.section_details[n];
      return { n: Number(n), name, first: d.hadithnumber_first, last: d.hadithnumber_last };
    })
    .filter((s) => s.last >= s.first && s.first > 0);
  return {
    key, name: e.name,
    editions: e.collection.map((c) => c.name).filter((n) => !/\d$/.test(n)),
    max: Math.max(...nums), sections,
  };
});

const books = (await get("https://www.thaqalayn-api.net/api/v2/allbooks"))
  .filter((b) => !SHIA_SKIP.has(b.bookId))
  .map((b) => ({ id: b.bookId, name: b.BookName, english: b.englishName, author: b.author, translator: b.translator, volume: b.volume, max: b.idRangeMax }));

const out = `// Generated by scripts/sync-hadith.mjs on ${new Date().toISOString().slice(0, 10)} – do not edit by hand.
// Metadata only (names, books, number ranges); the texts come from the APIs at run time.
export type SunniCollection = { key: string; name: string; editions: string[]; max: number; sections: { n: number; name: string; first: number; last: number }[] };
export type ShiaBook = { id: string; name: string; english: string; author: string; translator: string; volume: number; max: number };
export const SUNNI_COLLECTIONS: SunniCollection[] = ${JSON.stringify(sunni)};
export const SHIA_BOOKS: ShiaBook[] = ${JSON.stringify(books)};
`;
writeFileSync(join(root, "src/features/hadith/catalog.ts"), out);
console.log("sunni", sunni.map((c) => `${c.key}:${c.sections.length}/${c.max}`).join(" "), "shia", books.length);
